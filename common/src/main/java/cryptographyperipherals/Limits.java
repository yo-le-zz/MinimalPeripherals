package cryptographyperipherals;

/** Fixed limits (the original mod exposed some of these through a config file). */
public final class Limits {
    /** Maximum size of the buffer returned by randomBytes. */
    public static final int RANDOM_BYTES_MAX_SIZE = 65536;
    /** Maximum output size of blake3, in bytes. */
    public static final int BLAKE3_MAX_OUTPUT = 4096;
    /** Maximum output size of the key derivation functions (pbkdf2, hkdf, scrypt), in bytes. */
    public static final int KDF_MAX_OUTPUT = 1024;
    /** Maximum iteration count of pbkdf2. */
    public static final int PBKDF2_MAX_ITERATIONS = 1_000_000;
    /** Maximum scrypt cost parameters. */
    public static final int SCRYPT_MAX_N = 1 << 15;
    public static final int SCRYPT_MAX_R = 8;
    public static final int SCRYPT_MAX_P = 4;
    /** Maximum size of the data produced by inflate / gunzip (protects against decompression bombs). */
    public static final int INFLATE_MAX_SIZE = 8 * 1024 * 1024;

    /** Maximum number of items accepted by the batch functions (many, signMany, ...). */
    public static final int BATCH_MAX_ITEMS = 10_000;
    /** Maximum rounds of the chain function of the hash engines. */
    public static final int HASH_CHAIN_MAX_ROUNDS = 1_000_000;
    /** Maximum attempts of one pow_miner.mine call. */
    public static final int POW_MAX_ITERATIONS = 5_000_000;
    /** Default and maximum pbkdf2 iterations of the password hasher. */
    public static final int PASSWORD_DEFAULT_ITERATIONS = 120_000;
    /** Maximum input of base58 (its cost grows with the square of the size). */
    public static final int BASE58_MAX_INPUT = 4096;
    /** Maximum length of the strings generated by entropy_source.token. */
    public static final int TOKEN_MAX_LENGTH = 4096;
    /** Maximum number of dice of entropy_source.dice. */
    public static final int DICE_MAX_COUNT = 1000;

    private Limits() {
    }
}
